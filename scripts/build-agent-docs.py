def _plain_text(source: Path) -> str:
    value = source.read_text(encoding="utf-8")
    value = re.sub(r"```.*?```", " ", value, flags=re.DOTALL)
    value = LINK_RE.sub(r"\1", value)
    # Strip block/list markers without corrupting filenames and CLI identifiers.
    value = re.sub(r"(?m)^\s*(?:#{1,6}\s+|[-*+]\s+|>\s*)", " ", value)
    value = re.sub(r"[*`|\[\]]+", " ", value)
    return re.sub(r"\s+", " ", value).strip()


def _expected_outputs() -> dict[Path, str]:
    outputs = {page.output_path: _render_page(page) for page in PAGES}
    search_index = [
        {
            "title": page.label,
            "category": page.category,
            "description": page.description,
            "url": page.url,
            "text": _plain_text(page.source_path),
        }
        for page in PAGES
    ]
    outputs[ASSET_ROOT / "search-index.json"] = json.dumps(search_index, ensure_ascii=False, indent=2) + "\n"
    return outputs


def build(check: bool) -> int:
    missing_sources = [str(page.source_path) for page in PAGES if not page.source_path.is_file()]
    missing_assets = [str(path) for path in (ASSET_ROOT / "docs.css", ASSET_ROOT / "docs.js") if not path.is_file()]
    if missing_sources or missing_assets:
        for path in missing_sources + missing_assets:
            print(f"missing: {path}", file=sys.stderr)
        return 1

    drift: list[Path] = []
    for path, expected in _expected_outputs().items():
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                drift.append(path)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(expected, encoding="utf-8", newline="\n")

    if drift:
        for path in drift:
            print(f"out of date: {path.relative_to(REPO)}", file=sys.stderr)
        print("run: python scripts/build-agent-docs.py", file=sys.stderr)
        return 1
    if check:
        print(f"agent docs current: {len(PAGES)} pages")
    else:
        print(f"agent docs built: {len(PAGES)} pages")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when generated docs differ")
    return build(parser.parse_args().check)


if __name__ == "__main__":
    raise SystemExit(main())

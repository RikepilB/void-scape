HEADING_RE = re.compile(r"^(#{1,4})\s+(.+?)\s*$")
LIST_RE = re.compile(r"^(\s*)([-*]|\d+\.)\s+(.+)$")
TABLE_SEPARATOR_RE = re.compile(r"^\s*\|?\s*:?-{3,}")
FENCE_RE = re.compile(r"^\s*```\s*([\w+-]*)\s*$")
LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)]+)\)")
CODE_RE = re.compile(r"`([^`]+)`")
STRONG_RE = re.compile(r"\*\*(.+?)\*\*")
BACK_LINK_RE = re.compile(r"^\[Back to agent docs\]\([^)]+\)\s*·?\s*", re.IGNORECASE)


def _slug(value: str) -> str:
    value = re.sub(r"`([^`]+)`", r"\1", value)
    value = re.sub(r"\[([^\]]+)\]\([^)]+\)", r"\1", value)
    value = re.sub(r"<[^>]+>", "", value)
    value = value.casefold().replace("&", " and ")
    value = re.sub(r"[^a-z0-9]+", "-", value).strip("-")
    return value or "section"


def _relative_url(current_output: Path, target: Path) -> str:
    return Path(os.path.relpath(target, current_output.parent)).as_posix()


def _rewrite_link(url: str, current_source: Path) -> str:
    parsed = urlsplit(url)
    if parsed.scheme or parsed.netloc or url.startswith(("#", "mailto:")):
        return url
    target = (current_source.parent / parsed.path).resolve()
    try:
        relative_source = target.relative_to(SOURCE_ROOT.resolve())
    except ValueError:
        relative_source = None
    if relative_source is not None:
        if target.suffix.casefold() != ".md":
            return url
        current_output = current_source.with_suffix(".html")
        target_output = (SOURCE_ROOT / relative_source).with_suffix(".html")
        path = _relative_url(current_output, target_output)
        return urlunsplit(("", "", path, parsed.query, parsed.fragment))

    # The public deployment serves docs/, not repository-root files. Keep source and
    # contract links usable by sending those resolved repository paths to GitHub.
    try:
        repository_path = target.relative_to(REPO.resolve())
    except ValueError:
        return url
    if not target.is_file():
        return url
    github_path = quote(repository_path.as_posix(), safe="/")
    return urlunsplit(("https", "github.com", f"/RikepilB/void-scape/blob/main/{github_path}", parsed.query, parsed.fragment))


def _inline(value: str, current_source: Path) -> str:
    tokens: dict[str, str] = {}

    def stash(rendered: str) -> str:
        key = f"@@VOIDSCAPE_TOKEN_{len(tokens)}@@"
        tokens[key] = rendered
        return key

    def code(match: re.Match[str]) -> str:
        return stash(f"<code>{html.escape(match.group(1))}</code>")

    def link(match: re.Match[str]) -> str:
        label = html.escape(match.group(1))
        label = CODE_RE.sub(r"<code>\1</code>", label)
        href = _rewrite_link(match.group(2), current_source)
        attrs = ""
        if href.startswith(("http://", "https://")):
            attrs = ' target="_blank" rel="noreferrer"'
        return stash(f'<a href="{html.escape(href, quote=True)}"{attrs}>{label}</a>')

    value = LINK_RE.sub(link, value)
    value = CODE_RE.sub(code, value)
    value = html.escape(value)
    value = STRONG_RE.sub(r"<strong>\1</strong>", value)
    for key, rendered in tokens.items():
        value = value.replace(key, rendered)
    return value


def _is_block_start(lines: list[str], index: int) -> bool:
    line = lines[index]
    stripped = line.strip()
    if not stripped:
        return True
    if HEADING_RE.match(line) or FENCE_RE.match(line) or LIST_RE.match(line):
        return True
    if stripped == "---" or stripped.startswith("> "):
        return True
    return index + 1 < len(lines) and "|" in line and TABLE_SEPARATOR_RE.match(lines[index + 1]) is not None


def _table_cells(line: str) -> list[str]:
    return [cell.strip() for cell in line.strip().strip("|").split("|")]


def _render_markdown(source: Path) -> tuple[str, str, list[tuple[int, str, str]]]:
    lines = source.read_text(encoding="utf-8").splitlines()
    title = source.stem.replace("-", " ").title()
    body: list[str] = []
    toc: list[tuple[int, str, str]] = []
    used_slugs: dict[str, int] = {}
    i = 0

    while i < len(lines):
        line = lines[i]
        stripped = line.strip()
        if not stripped:
            i += 1
            continue

        heading = HEADING_RE.match(line)
        if heading:
            level = len(heading.group(1))
            text = heading.group(2).strip()
            if level == 1:
                title = re.sub(r"[`*_]", "", text)
                i += 1
                continue
            base_slug = _slug(text)
            count = used_slugs.get(base_slug, 0)
            used_slugs[base_slug] = count + 1
            anchor = base_slug if count == 0 else f"{base_slug}-{count + 1}"
            toc.append((level, re.sub(r"[`*_]", "", text), anchor))
            body.append(
                f'<h{level} id="{anchor}">{_inline(text, source)}'
                f'<a class="heading-anchor" href="#{anchor}" aria-label="Link to {html.escape(text, quote=True)}">#</a>'
                f"</h{level}>"
            )
            i += 1
            continue

        fence = FENCE_RE.match(line)
        if fence:
            language = fence.group(1).casefold()
            code_lines: list[str] = []
            i += 1
            while i < len(lines) and FENCE_RE.match(lines[i]) is None:
                code_lines.append(lines[i])
                i += 1
            if i < len(lines):
                i += 1
            labels = {"powershell": "PowerShell", "bash": "Shell", "json": "JSON", "text": "Protocol"}
            label = labels.get(language, language.upper() if language else "Terminal")
            code_text = "\n".join(code_lines).strip("\n")
            body.append(
                '<div class="code-block">'
                f'<div class="code-meta"><span>{html.escape(label)}</span>'
                '<button class="copy-button" type="button">Copy</button></div>'
                f'<pre><code class="language-{html.escape(language)}">{html.escape(code_text)}</code></pre>'
                "</div>"
            )
            continue

        if i + 1 < len(lines) and "|" in line and TABLE_SEPARATOR_RE.match(lines[i + 1]):
            headers = _table_cells(line)
            i += 2
            rows: list[list[str]] = []
            while i < len(lines) and lines[i].strip() and "|" in lines[i]:
                rows.append(_table_cells(lines[i]))
                i += 1
            rendered_headers = "".join(f"<th scope=\"col\">{_inline(cell, source)}</th>" for cell in headers)
            rendered_rows = []
            for row in rows:
                padded = row + [""] * max(0, len(headers) - len(row))
                rendered_rows.append("<tr>" + "".join(f"<td>{_inline(cell, source)}</td>" for cell in padded[: len(headers)]) + "</tr>")
            body.append(
                '<div class="table-scroll"><table><thead><tr>' + rendered_headers
                + "</tr></thead><tbody>" + "".join(rendered_rows) + "</tbody></table></div>"
            )
            continue

        list_match = LIST_RE.match(line)
        if list_match:
            ordered = list_match.group(2).endswith(".")
            tag = "ol" if ordered else "ul"
            items: list[str] = []
            while i < len(lines):
                match = LIST_RE.match(lines[i])
                if match is None or match.group(2).endswith(".") != ordered:
                    break
                item_parts = [match.group(3).strip()]
                i += 1
                while i < len(lines) and lines[i].strip() and LIST_RE.match(lines[i]) is None and not _is_block_start(lines, i):
                    item_parts.append(lines[i].strip())
                    i += 1
                items.append(" ".join(item_parts))
            body.append(f"<{tag}>" + "".join(f"<li>{_inline(item, source)}</li>" for item in items) + f"</{tag}>")
            continue

        if stripped.startswith("> "):
            quote: list[str] = []
            while i < len(lines) and lines[i].strip().startswith("> "):
                quote.append(lines[i].strip()[2:])
                i += 1
            body.append(f'<aside class="callout">{_inline(" ".join(quote), source)}</aside>')
            continue

        if stripped == "---":
            body.append("<hr>")
            i += 1
            continue

        paragraph = [stripped]
        i += 1
        while i < len(lines) and lines[i].strip() and not _is_block_start(lines, i):
            paragraph.append(lines[i].strip())
            i += 1
        text = " ".join(paragraph)
        source_note = BACK_LINK_RE.sub("", text)
        if source_note != text:
            if source_note:
                body.append(f'<p class="source-note">{_inline(source_note, source)}</p>')
            continue
        css_class = ' class="status-line"' if text.startswith("**Status:**") else ""
        body.append(f"<p{css_class}>{_inline(text, source)}</p>")

    return title, "\n".join(body), toc


def _nav_html(current: Page) -> str:
    groups: list[str] = []
    categories: list[str] = []
    for page in PAGES:
        if page.category not in categories:
            categories.append(page.category)
    for category in categories:
        links = []
        for page in (item for item in PAGES if item.category == category):
            href = _relative_url(current.output_path, page.output_path)
            active = ' class="active" aria-current="page"' if page == current else ""
            links.append(f'<a href="{href}"{active}>{html.escape(page.label)}</a>')
        groups.append(
            '<details class="nav-group" open>'
            f"<summary>{html.escape(category)}</summary>"
            f'<div class="nav-links">{"".join(links)}</div>'
            "</details>"
        )
    manifest_href = _relative_url(current.output_path, SOURCE_ROOT / "manifest.json")
    groups.append(
        '<div class="nav-utility">'
        f'<a href="{manifest_href}"><span>JSON</span> Discovery manifest</a>'
        "</div>"
    )
    return "\n".join(groups)


def _toc_html(toc: list[tuple[int, str, str]]) -> str:
    links = ['<a href="#top" class="toc-level-2">Overview</a>']
    links.extend(
        f'<a href="#{anchor}" class="toc-level-{level}">{html.escape(text)}</a>'
        for level, text, anchor in toc
        if level <= 3
    )
    return "\n".join(links)


def _page_navigation(current: Page) -> str:
    index = PAGES.index(current)
    links = []
    if index > 0:
        previous = PAGES[index - 1]
        href = _relative_url(current.output_path, previous.output_path)
        links.append(f'<a class="previous" href="{href}"><span>Previous</span><strong>← {html.escape(previous.label)}</strong></a>')
    if index < len(PAGES) - 1:
        following = PAGES[index + 1]
        href = _relative_url(current.output_path, following.output_path)
        links.append(f'<a class="next" href="{href}"><span>Next</span><strong>{html.escape(following.label)} →</strong></a>')
    return "".join(links)


